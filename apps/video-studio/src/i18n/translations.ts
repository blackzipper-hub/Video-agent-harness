export type Language = keyof typeof translations
export type TranslationKey = keyof typeof translations.en

/** 后端 detected_language（ISO 639-1）映射为前端 UI 语言，用于 user_input 或 conversation.detail 后切换界面语言 */
export function mapBackendLanguageToUi(backend: string | undefined | null): Language {
  if (!backend || typeof backend !== 'string') return 'en'
  const lower = backend.trim().toLowerCase()
  if (lower === 'zh' || lower.startsWith('zh-')) return 'zh'
  return 'en'
}
